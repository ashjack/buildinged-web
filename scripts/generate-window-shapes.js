// Extracts the WindowShape tile property from Project Zomboid's tile definitions into
// src/app/utils/window-shapes.data.ts. Usage: node scripts/generate-window-shapes.js [path/to/*.tiles ...]
const fs = require('fs');
const path = require('path');

const files = process.argv.slice(2);
if (!files.length) files.push('C:/Program Files (x86)/Steam/steamapps/common/ProjectZomboid/media/newtiledefinitions.tiles');

const shapes = new Map(); // tileset -> Map(index -> shape)
for (const file of files) {
  const buffer = fs.readFileSync(file);
  let offset = 0;
  const int = () => { const value = buffer.readInt32LE(offset); offset += 4; return value; };
  const line = () => { const end = buffer.indexOf(10, offset); const text = buffer.toString('latin1', offset, end); offset = end + 1; return text; };
  let version = 0;
  if (buffer.toString('latin1', 0, 4) === 'tdef') { offset = 4; version = int(); }
  const tilesets = int();
  for (let t = 0; t < tilesets; t++) {
    const name = line(); line(); int(); int();
    if (version > 0) int();
    const count = int();
    for (let i = 0; i < count; i++) {
      const properties = int();
      for (let p = 0; p < properties; p++) {
        const key = line(), value = line();
        if (key !== 'WindowShape' || !/^\d+$/.test(value)) continue;
        if (!shapes.has(name)) shapes.set(name, new Map());
        shapes.get(name).set(i, Number(value));
      }
    }
  }
}

// Runs of consecutive indices sharing a shape: [first index, count, shape].
const data = {};
for (const name of [...shapes.keys()].sort()) {
  const runs = [];
  for (const [index, shape] of [...shapes.get(name)].sort((a, b) => a[0] - b[0])) {
    const last = runs[runs.length - 1];
    if (last && last[0] + last[1] === index && last[2] === shape) last[1]++;
    else runs.push([index, 1, shape]);
  }
  data[name] = runs;
}
const out = path.join(__dirname, '../src/app/utils/window-shapes.data.ts');
fs.writeFileSync(out, '// Generated by scripts/generate-window-shapes.js from the game\'s tile definitions. Do not edit.\n'
  + '// tileset -> runs of [first tile index, count, WindowShape]\n'
  + 'export const WINDOW_SHAPE_RUNS: Readonly<Record<string, readonly (readonly [number, number, number])[]>> = {\n'
  + Object.entries(data).map(([name, runs]) => `  ${name}: ${JSON.stringify(runs)},`).join('\n') + '\n};\n');
console.log(`${Object.keys(data).length} tilesets, ${[...shapes.values()].reduce((n, m) => n + m.size, 0)} tiles -> ${out}`);
